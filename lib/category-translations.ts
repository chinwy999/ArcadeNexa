export function getCategoryTranslation(
  slug: string,
  locale: Locale
): CategoryTranslation | null {
  if (locale === 'ar') {
    return ar[slug] ?? null
  }

  return null
}

export function getLocalizedCategoryName(
  slug: string,
  fallback: string,
  locale: Locale
): string {
  return locale === 'ar' ? ar[slug]?.name ?? fallback : fallback
}

